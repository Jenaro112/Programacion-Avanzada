/**
 * 2. Array Bidimensional:
 * Crea un array bidimensional llamado matriz con los valores [[1, 2, 3],
 * [4, 5, 6], [7, 8, 9]]. Accede al elemento 5 e imprímelo en la consola.
 */

const matriz = [
  [1, 2, 3],
  [4, 5, 6],
  [7, 8, 9]
];

console.log("--- Punto 2: Array Bidimensional ---");
console.log("Matriz completa:", matriz);

// El elemento 5 se encuentra en la fila índice 1, columna índice 1
const elementoCinco = matriz[1][1];
console.log("Elemento accedido (matriz[1][1]):", elementoCinco);
