/**
 * 2. Función que Multiplica:
 * Crea una función llamada multiplicar que tome dos números como
 * parámetros y devuelva su producto. Prueba la función con diferentes
 * valores.
 */

function multiplicar(a, b) {
  return a * b;
}

console.log("--- Punto 2: Función que Multiplica ---");
console.log("4 * 5 =", multiplicar(4, 5));
console.log("7 * (-3) =", multiplicar(7, -3));
console.log("0 * 100 =", multiplicar(0, 100));
