/**
 * 1. Función Suma:
 * Crea una función llamada sumar que tome dos números como
 * parámetros y devuelva su suma. Prueba la función con diferentes
 * números.
 */

function sumar(a, b) {
  return a + b;
}

console.log("--- Punto 1: Función Suma ---");
console.log("5 + 3 =", sumar(5, 3));
console.log("10 + (-4) =", sumar(10, -4));
console.log("2.5 + 7.5 =", sumar(2.5, 7.5));
