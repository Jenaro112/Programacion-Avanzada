/**
 * 10. Función Anónima:
 * Crea una función anónima que sume dos números y la asigna a una
 * variable llamada sumarAnonima. Luego, invoca la función a través de
 * esa variable.
 */

const sumarAnonima = function (a, b) {
  return a + b;
};

console.log("--- Punto 10: Función Anónima ---");
const resultado = sumarAnonima(15, 25);
console.log("Resultado de sumarAnonima(15, 25):", resultado);
